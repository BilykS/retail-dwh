create schema if not exists star;

create table if not exists star.dim_transaction_type (
    transaction_type_key integer generated always as identity primary key,
    channel text not null,
    order_type text not null,
    payment_method text not null,
    unique (channel, payment_method, order_type)
);

create table if not exists star.dim_date (
    date_key    integer primary key,
    full_date   date    not null,
    year        integer not null,
    quarter     integer not null,
    month       integer not null,
    month_name  text    not null,
    day         integer not null,
    day_of_week integer not null,
    day_name    text    not null,
    is_weekend  bool    not null
);

create table if not exists star.dim_product (
    product_key     integer generated always as identity primary key,
    product_id      integer not null unique,
    sku             text not null unique,
    product_name    text not null,
    category_name   text not null,
    category_parent text not null,
    brand_name      text not null,
    unit_cost       numeric(12,2) not null
);

create table if not exists star.dim_store (
    store_key  integer generated always as identity primary key,
    store_id   integer not null unique,
    store_code text not null unique,
    store_name text not null,
    city_name  text not null,
    region     text not null,
    store_type text not null,
    opened_at  date not null,
    closed_at  date
);

create table if not exists star.dim_customer (
    customer_key integer generated by default as identity  primary key,
    customer_id integer not null unique,
    full_name   text not null,
    email       text,
    phone       text,
    birth_date  date,
    gender      text not null,
    city        text not null,
    loyalty_tier text not null,
    main_shopping_city text
);

create table if not exists star.fact_sales (
    fact_key             bigint  generated always as identity primary key,
    order_item_id        integer not null unique,
    date_key             integer not null references star.dim_date(date_key),
    product_key          integer not null references star.dim_product(product_key),
    store_key            integer not null references star.dim_store(store_key),
    customer_key         integer not null references star.dim_customer(customer_key),
    transaction_type_key integer not null references star.dim_transaction_type(transaction_type_key),
    hour                 integer not null,
    order_number         text    not null,
    quantity             integer not null,
    gross_amount         numeric(12,2) not null,
    discount_amount      numeric(12,2) not null,
    net_amount           numeric(12,2) not null,
    cost_amount          numeric(12,2) not null
);