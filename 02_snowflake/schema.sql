create schema if not exists snow;

create table if not exists snow.dim_transaction_type (like star.dim_transaction_type including all);
create table if not exists snow.dim_date (like star.dim_date including all);

create table if not exists snow.dim_region (
    region_key  integer generated by default as identity primary key,
    region_name text not null unique
);

create table if not exists snow.dim_category_group (
    category_group_key  integer generated always as identity primary key,
    category_group_id   integer not null unique, 
    category_group_name text not null
  
);

create table if not exists snow.dim_brand (
    brand_key   integer generated always as identity primary key,
    brand_id    integer not null unique,
    brand_name  text not null,
    country     text not null
);

create table if not exists snow.dim_city (
    city_key    integer generated by default as identity primary key,
    city_id     integer not null unique,
    city_name   text not null,
    region_key  integer not null references snow.dim_region(region_key)
);

create table if not exists snow.dim_category (
    category_key        integer generated always as identity primary key,
    category_id         integer not null unique,
    category_name       text not null,
    category_group_key  integer not null references snow.dim_category_group(category_group_key)
);

create table if not exists snow.dim_product (
    product_key     integer generated always as identity primary key,
    product_id      integer not null unique,
    sku             text not null unique,
    product_name    text not null,
    category_key    integer not null references snow.dim_category(category_key),
    brand_key       integer not null references snow.dim_brand(brand_key),
    unit_cost       numeric(12,2) not null
);

create table if not exists snow.dim_store (
    store_key  integer generated always as identity primary key,
    store_id   integer not null unique,
    store_code text not null unique,
    store_name text not null,
    city_key   integer not null references snow.dim_city(city_key),
    store_type text not null,
    opened_at  date not null,
    closed_at  date
);

create table if not exists snow.dim_customer (
    customer_key integer generated by default as identity  primary key,
    customer_id integer not null unique,
    full_name   text not null,
    email       text,
    phone       text,
    birth_date  date,
    gender      text not null,
    city_key    integer not null references snow.dim_city(city_key),
    loyalty_tier text not null,
    main_shopping_city_key integer references snow.dim_city(city_key)
);

create table if not exists snow.fact_sales (
    fact_key             bigint  generated always as identity primary key,
    order_item_id        integer not null unique,
    date_key             integer not null references snow.dim_date(date_key),
    product_key          integer not null references snow.dim_product(product_key),
    store_key            integer not null references snow.dim_store(store_key),
    customer_key         integer not null references snow.dim_customer(customer_key),
    transaction_type_key integer not null references snow.dim_transaction_type(transaction_type_key),
    hour                 integer not null,
    order_number         text    not null,
    quantity             integer not null,
    gross_amount         numeric(12,2) not null,
    discount_amount      numeric(12,2) not null,
    net_amount           numeric(12,2) not null,
    cost_amount          numeric(12,2) not null
);