#!/usr/bin/env node
/**
 * Downloads the self-hosted fonts into public/fonts/ and writes the matching
 * @font-face CSS to src/styles/fonts.css.
 *
 * Why self-host: a third-party request on every load adds latency to the first
 * render and hands the reader's IP to someone else. The files are OFL licensed.
 *
 * Half of this site is Ukrainian, so the Cyrillic subsets are required. Without
 * them the /uk pages silently fall back to system fonts. unicode-range keeps the
 * cost at zero for readers who never need them.
 *
 * Run: node scripts/fetch-fonts.mjs
 */

import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(SITE, 'public', 'fonts');

// A modern User-Agent is required, otherwise Google serves ttf instead of woff2.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const FAMILIES = [
  { css: 'Source+Sans+3:wght@400;500;600', slug: 'source-sans-3', name: 'Source Sans 3' },
  { css: 'Source+Serif+4:wght@400', slug: 'source-serif-4', name: 'Source Serif 4' },
  { css: 'JetBrains+Mono:wght@400;500', slug: 'jetbrains-mono', name: 'JetBrains Mono' },
];

const WANTED_SUBSETS = new Set(['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext']);

async function fetchCss(family) {
  const url = `https://fonts.googleapis.com/css2?family=${family}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

/** Splits Google's CSS into blocks, each preceded by a subset-name comment. */
function parseBlocks(css) {
  const blocks = [];
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  for (const m of css.matchAll(re)) {
    const [, subset, body] = m;
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1].trim() ?? 'normal';
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1].trim() ?? '400';
    const src = /url\((https:\/\/[^)]+\.woff2)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim();
    if (src) blocks.push({ subset, style, weight, src, range });
  }
  return blocks;
}

mkdirSync(OUT, { recursive: true });

const faces = [];
let downloaded = 0;
let skipped = 0;

for (const { css, slug, name } of FAMILIES) {
  const blocks = parseBlocks(await fetchCss(css)).filter((b) => WANTED_SUBSETS.has(b.subset));
  if (!blocks.length) throw new Error(`${slug}: none of the wanted subsets were found`);

  for (const b of blocks) {
    const file = `${slug}-${b.weight}-${b.subset}.woff2`;
    const dest = join(OUT, file);

    if (existsSync(dest)) {
      skipped++;
    } else {
      const bin = await fetch(b.src, { headers: { 'User-Agent': UA } });
      if (!bin.ok) throw new Error(`${b.src}: HTTP ${bin.status}`);
      writeFileSync(dest, Buffer.from(await bin.arrayBuffer()));
      downloaded++;
    }

    faces.push(
      [
        '@font-face {',
        `  font-family: "${name}";`,
        `  font-style: ${b.style};`,
        `  font-weight: ${b.weight};`,
        '  font-display: swap;',
        `  src: url("/fonts/${file}") format("woff2");`,
        b.range ? `  unicode-range: ${b.range};` : null,
        '}',
      ]
        .filter(Boolean)
        .join('\n'),
    );
  }
  console.log(`  ${slug}: ${blocks.length} files`);
}

const out = `/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n${faces.join('\n\n')}\n`;
writeFileSync(join(SITE, 'src', 'styles', 'fonts.css'), out, 'utf8');
console.log(`\nDownloaded ${downloaded}, already present ${skipped}.`);
