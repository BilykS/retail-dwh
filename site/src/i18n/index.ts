/**
 * Two-locale setup: English at the root, Ukrainian under /uk.
 *
 * Short UI strings live here. Prose lives next to the page that uses it, where
 * the two languages sit side by side and are easier to keep honest.
 */

export const LOCALES = ['en', 'uk'] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = 'en';

export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  uk: 'Українська',
};

/** Short label for the header switcher. */
export const LOCALE_SHORT: Record<Locale, string> = {
  en: 'EN',
  uk: 'UA',
};

/** Builds a path for a locale: ("uk", "/report") becomes "/uk/report". */
export function localePath(lang: Locale, path: string): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  if (lang === DEFAULT_LOCALE) return clean;
  return clean === '/' ? `/${lang}` : `/${lang}${clean}`;
}

/** Strips the locale prefix so the same page can be linked in the other language. */
export function pathWithoutLocale(pathname: string): string {
  const parts = pathname.replace(/\.html?$/i, '').split('/').filter(Boolean);
  if ((LOCALES as readonly string[]).includes(parts[0] ?? '')) parts.shift();
  return '/' + parts.join('/');
}

